#!/usr/bin/env bash
# Load one KG release into a NEW Neo4j data directory. Runs INSIDE the neo4j image
# (apptainer exec on HPC3, `docker compose run` on a Docker host, a Job on Kubernetes).
#
#   1. neo4j-admin database import full into <target>.partial/data (never touches a served store)
#   2. set the initial neo4j password from a file (via an @argfile, never on argv)
#   3. start a temporary server on 127.0.0.1:<load port>, apply post_import.cypher, await indexes
#   4. count nodes/relationships, stop the server, rename <target>.partial -> <target>, write LOADED.json
#
# Inputs (environment):
#   VISIONKB_KG_RELEASE      release id (required; must match <release>/RELEASE)
#   VISIONKB_RELEASE_DIR     unpacked, verified release (default /release; read-only is fine)
#   VISIONKB_TARGET_DIR      final per-release folder, e.g. /releases/<id> (required; must not exist)
#   NEO4J_PASSWORD_FILE      neo4j password file (default /run/secrets/neo4j_password)
#   VISIONKB_LOAD_BOLT_PORT  bolt port of the temporary server (default 17687)
#   VISIONKB_LOAD_HEAP, VISIONKB_LOAD_PAGECACHE   memory of import + temporary server (default 1g / 512m)
#   VISIONKB_TMP_DIR         writable scratch (default /tmp)
#   VISIONKB_START_TIMEOUT, VISIONKB_INDEX_TIMEOUT   seconds (default 300 / 600)
#   VISIONKB_EXPECTED_IDS_DIR  nodes.ids + rels.ids from `bundle.py expected-ids` (the import CSVs); the loaded
#                            store's node ids and relationship keys must match them byte for byte
#   VISIONKB_REQUIRE_ID_CHECK  1 (default): fail when VISIONKB_EXPECTED_IDS_DIR is missing
set -euo pipefail

die() {
  echo "neo4j-load-release: error: $*" >&2
  exit 1
}
log() { echo "neo4j-load-release: $*" >&2; }

release="${VISIONKB_KG_RELEASE:?VISIONKB_KG_RELEASE is required}"
src="${VISIONKB_RELEASE_DIR:-/release}"
target="${VISIONKB_TARGET_DIR:?VISIONKB_TARGET_DIR is required}"
pwfile="${NEO4J_PASSWORD_FILE:-/run/secrets/neo4j_password}"
port="${VISIONKB_LOAD_BOLT_PORT:-17687}"
heap="${VISIONKB_LOAD_HEAP:-1g}"
pagecache="${VISIONKB_LOAD_PAGECACHE:-512m}"
tmp="${VISIONKB_TMP_DIR:-/tmp}"
start_timeout="${VISIONKB_START_TIMEOUT:-300}"
index_timeout="${VISIONKB_INDEX_TIMEOUT:-600}"
expected="${VISIONKB_EXPECTED_IDS_DIR:-}"
require_ids="${VISIONKB_REQUIRE_ID_CHECK:-1}"
neo4j_home="${NEO4J_HOME:-/var/lib/neo4j}"

[[ "$release" =~ ^visionkb-[0-9]{4}\.[0-9]{2}\.[0-9]+$ ]] || die "invalid release id: $release"
[[ "$port" =~ ^[0-9]+$ ]] || die "invalid VISIONKB_LOAD_BOLT_PORT: $port"
[[ -f "$src/RELEASE" ]] || die "$src/RELEASE missing (is the release mounted at $src?)"
[[ "$(tr -d '[:space:]' <"$src/RELEASE")" == "$release" ]] || die "$src/RELEASE does not say $release"
imp="$src/neo4j-import"
[[ -f "$imp/import.args" && -f "$imp/post_import.cypher" ]] || die "$imp/import.args or post_import.cypher missing"
[[ -r "$pwfile" ]] || die "password file $pwfile not readable"
password="$(tr -d '\r\n' <"$pwfile")"
[[ "$password" =~ ^[A-Za-z0-9._~-]{8,}$ ]] || die "password must be >= 8 chars of [A-Za-z0-9._~-] (generated by 'visionkb init')"
[[ -e "$target" ]] && die "$target exists; refusing to overwrite a loaded release"
if [[ -n "$expected" ]]; then
  [[ -f "$expected/nodes.ids" && -f "$expected/rels.ids" ]] || die "VISIONKB_EXPECTED_IDS_DIR=$expected lacks nodes.ids/rels.ids"
elif [[ "$require_ids" != 0 ]]; then
  die "no expected ids (VISIONKB_EXPECTED_IDS_DIR); run bundle.py expected-ids or set VISIONKB_REQUIRE_ID_CHECK=0"
fi

partial="${target}.partial"
rm -rf "$partial"
mkdir -p "$partial/data" "$partial/load-logs"
work="$(mktemp -d "$tmp/visionkb-load.XXXXXX")"
umask 077
mkdir -p "$work/conf" "$work/run"

server_started=0
cleanup() {
  local rc=$?
  if [[ "$server_started" == 1 ]]; then
    NEO4J_CONF="$work/conf" neo4j stop >/dev/null 2>&1 || true
  fi
  rm -rf "$work"
  if [[ $rc -ne 0 ]]; then
    log "FAILED (exit $rc); partial store kept for inspection at $partial"
  fi
}
trap cleanup EXIT

# --- configuration for neo4j-admin and the temporary server -------------------------------------
cp "$neo4j_home"/conf/* "$work/conf/"
declare -A settings=(
  [server.directories.data]="$partial/data"
  [server.directories.logs]="$partial/load-logs"
  [server.directories.run]="$work/run"
  [server.directories.import]="$imp"
  [server.default_listen_address]="127.0.0.1"
  [server.bolt.listen_address]="127.0.0.1:$port"
  [server.http.enabled]="false"
  [server.https.enabled]="false"
  [server.memory.heap.initial_size]="$heap"
  [server.memory.heap.max_size]="$heap"
  [server.memory.pagecache.size]="$pagecache"
  [server.databases.default_to_read_only]="false"
  [dbms.security.auth_enabled]="true"
  # Neo4j 2026.10 defaults: no Fleet Manager, no UDP discovery broadcasts on the node's networks, no usage reports
  [server.fleet_discovery.enabled]="false"
  [dbms.fleet_manager.enabled]="false"
  [dbms.usage_report.enabled]="false"
)
conf="$work/conf/neo4j.conf"
for key in "${!settings[@]}"; do
  grep -v -E "^[[:space:]]*${key//./\\.}[[:space:]]*=" "$conf" >"$conf.tmp" || true
  mv "$conf.tmp" "$conf"
  printf '%s=%s\n' "$key" "${settings[$key]}" >>"$conf"
done
export NEO4J_CONF="$work/conf"

# --- 1. import ----------------------------------------------------------------------------------
# neo4j-admin needs absolute file paths; rewrite import.args with paths under $imp.
args="$work/import.args"
: >"$args"
while IFS= read -r line || [[ -n "$line" ]]; do
  line="${line#"${line%%[![:space:]]*}"}"
  line="${line%"${line##*[![:space:]]}"}"
  [[ -z "$line" || "$line" == \#* ]] && continue
  [[ "$line" == --* ]] || die "import.args: not an option line: $line"
  opt="${line%%=*}"
  case "$opt" in
  --overwrite-destination | --report-file | --additional-config | --expand-commands)
    die "import.args: option $opt is set by the loader and not allowed in a release"
    ;;
  --nodes | --relationships)
    [[ "$line" == *=* ]] || die "import.args: $opt needs '=<files>': $line"
    value="${line#*=}"
    spec="$value"
    prefix=""
    if [[ "$value" == *=* ]]; then
      prefix="${value%%=*}="
      spec="${value#*=}"
    fi
    IFS=',' read -r -a parts <<<"$spec"
    out=()
    for f in "${parts[@]}"; do
      [[ "$f" == /* || "$f" == *..* ]] && die "import.args: file paths must be relative to neo4j-import/: $f"
      out+=("$imp/${f#./}")
    done
    (
      IFS=,
      printf '%s=%s%s\n' "$opt" "$prefix" "${out[*]}"
    ) >>"$args"
    ;;
  *) printf '%s\n' "$line" >>"$args" ;;
  esac
done <"$imp/import.args"

log "importing $release from $src into $partial/data"
HEAP_SIZE="$heap" neo4j-admin database import full neo4j \
  --report-file="$partial/load-logs/import.report" "@$args" 2>&1 | { grep -v -E '^(WARNING: (Using incubator|Owner)|[.]{10} )' >&2 || true; }

# --- 2. initial password (argfile keeps it off the process list) ---------------------------------
printf '%s\n' "$password" >"$work/pw.args"
neo4j-admin dbms set-initial-password "@$work/pw.args" >/dev/null
rm -f "$work/pw.args"

# --- 3. temporary server, post_import.cypher ----------------------------------------------------
export NEO4J_PASSWORD="$password" # read by cypher-shell; this process only, never logged
cypher() { cypher-shell -a "bolt://127.0.0.1:$port" -u neo4j -d neo4j --format plain "$@"; }
log "starting temporary server on 127.0.0.1:$port"
neo4j start >"$partial/load-logs/start.out" 2>&1
server_started=1
deadline=$((SECONDS + start_timeout))
until cypher "RETURN 1" >/dev/null 2>&1; do
  ((SECONDS < deadline)) || die "temporary server not ready after ${start_timeout}s (see $partial/load-logs)"
  sleep 2
done
log "applying post_import.cypher"
cypher --fail-fast -f "$imp/post_import.cypher" >&2
cypher "CALL db.awaitIndexes($index_timeout)" >/dev/null
not_online="$(cypher "SHOW INDEXES YIELD state WHERE state <> 'ONLINE' RETURN count(*) AS n" | tail -n 1)"
[[ "$not_online" == 0 ]] || die "$not_online index(es) not ONLINE after post_import.cypher"
nodes="$(cypher "MATCH (n) RETURN count(n) AS n" | tail -n 1)"
rels="$(cypher "MATCH ()-[r]->() RETURN count(r) AS n" | tail -n 1)"
indexes="$(cypher "SHOW INDEXES YIELD name RETURN count(*) AS n" | tail -n 1)"
version="$(neo4j --version 2>/dev/null | tail -n 1)"

# --- ids: every node id and relationship key (start|type|end|id) must equal the import CSVs ------
# Counts alone miss corruption (e.g. stores written on a network filesystem: same count, garbled ids).
dump_keys() { cypher "$1" | tail -n +2 | LC_ALL=C sort >"$2"; }
log "dumping node ids and relationship keys"
dump_keys "MATCH (n) RETURN coalesce(n.id, '') AS k" "$work/nodes.ids"
dump_keys "MATCH (a)-[r]->(b) RETURN coalesce(a.id, '') + '|' + type(r) + '|' + coalesce(b.id, '') + '|' + coalesce(r.id, '') AS k" \
  "$work/rels.ids"
node_sha="$(sha256sum <"$work/nodes.ids" | cut -d' ' -f1)"
rel_sha="$(sha256sum <"$work/rels.ids" | cut -d' ' -f1)"
id_check=skipped
if [[ -n "$expected" ]]; then
  mismatch=0
  for k in nodes rels; do
    if ! cmp -s "$expected/$k.ids" "$work/$k.ids"; then
      mismatch=1
      log "$k: $(wc -l <"$expected/$k.ids") in the CSVs, $(wc -l <"$work/$k.ids") in the store; first differences:"
      LC_ALL=C comm -3 "$expected/$k.ids" "$work/$k.ids" | head -n 20 |
        sed -e 's/^\t/  only in the store: /' -e 't' -e 's/^/  only in the CSVs:  /' >&2
      cp "$work/$k.ids" "$partial/load-logs/$k.store.ids"
    fi
  done
  ((mismatch == 0)) || die "id check FAILED: the loaded store does not match the import CSVs (store kept at $partial)"
  id_check=ok
  log "id check ok: $(wc -l <"$work/nodes.ids") node ids, $(wc -l <"$work/rels.ids") relationship keys match the CSVs"
fi
neo4j stop >>"$partial/load-logs/start.out" 2>&1
server_started=0
unset NEO4J_PASSWORD

# --- 4. publish ---------------------------------------------------------------------------------
manifest_sha="$(sha256sum "$src/manifest.json" | cut -d' ' -f1)"
mv "$partial" "$target"
result="$(printf '{"kg_release":"%s","loaded_utc":"%s","nodes":%s,"relationships":%s,"indexes":%s,"neo4j_version":"%s","manifest_sha256":"%s","id_check":"%s","node_ids_sha256":"%s","rel_keys_sha256":"%s"}' \
  "$release" "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$nodes" "$rels" "$indexes" "$version" "$manifest_sha" "$id_check" "$node_sha" "$rel_sha")"
printf '%s\n' "$result" >"$target/LOADED.json"
log "loaded $release: $nodes nodes, $rels relationships, $indexes indexes -> $target"
echo "VISIONKB_LOAD_RESULT $result"
